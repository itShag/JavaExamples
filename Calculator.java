public class Calculator {


    public static double add(double a, double b) {
        return a + b;
    }
    
    public static double mult(double a, double b) {
        return a * b;
    }

    public static double divide(double a, double b) {
        return a / b;
    }

    public static double raznica(double a, double b) {
        return a - b;
    }
}
